"""McDowell's summary table pads single-digit days. The baker must still parse them.

A missing timestamp is an incomplete source: keep the last good file and exit 0.
Mapping bugs still fail.
"""
import importlib.util
import io
import shutil
import tempfile
import unittest
from datetime import datetime, timezone
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("stats", ROOT / "scripts/build-starlink-stats.py")
stats = importlib.util.module_from_spec(spec)
spec.loader.exec_module(stats)

PADDED = "Summary status table Data last updated: 2026 Nov  2 0045:00 <P>"
UNPADDED = "Data last updated: 2026 Oct 29 0144:51"
MARKDOWN = "Data last updated: 2026 Nov 2 0045:00"
HTML = "Data last updated:<br>2026 Nov&nbsp;&nbsp;2 0045:00"
NO_STAMP = (
    "<h2>Summary status table</h2>"
    "<p>Table briefly unavailable.</p>"
    "<h2>List of all Starlink satellites</h2>"
)
GOOD_JS = (
    "// Generated by scripts/build-starlink-stats.py. Do not edit by hand.\n"
    'window.STARLINK_LIVE = {"updated": "2026-10-29T01:44:51Z", "inOrbit": 11190};\n'
)
GOOD_HIST = '{"snapshots": [{"updated": "2026-10-29T01:44:51Z"}]}\n'


class TimestampTests(unittest.TestCase):
    def test_padded_single_digit_day(self):
        ts = stats.parse_updated(PADDED)
        self.assertEqual(ts, datetime(2026, 11, 2, 0, 45, 0, tzinfo=timezone.utc))
        self.assertIsNotNone(stats.TS_RE.search(PADDED))

    def test_two_digit_day_still_parses(self):
        ts = stats.parse_updated(UNPADDED)
        self.assertEqual(ts, datetime(2026, 10, 29, 1, 44, 51, tzinfo=timezone.utc))

    def test_unpadded_single_digit_and_html_nbsp(self):
        self.assertEqual(stats.parse_updated(MARKDOWN).day, 2)
        self.assertEqual(stats.parse_updated(HTML), datetime(2026, 11, 2, 0, 45, 0, tzinfo=timezone.utc))

    def test_missing_timestamp_does_not_guess_a_date(self):
        with self.assertRaises(stats.IncompleteSource) as ctx:
            stats.parse_updated("Summary status table with no date")
        self.assertEqual(str(ctx.exception), "no timestamp")


class KeepLastGoodTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        self.out = self.tmp / "starlink-live.js"
        self.out.write_text(GOOD_JS, encoding="utf-8")
        self.hist = self.tmp / "starlink-history.json"
        self.hist.write_text(GOOD_HIST, encoding="utf-8")
        self._out, self._hist = stats.OUT, stats.HIST
        stats.OUT, stats.HIST = self.out, self.hist
        self.addCleanup(self._restore)

    def _restore(self):
        stats.OUT, stats.HIST = self._out, self._hist

    def test_missing_timestamp_keeps_last_good_data_and_exits_zero(self):
        err = io.StringIO()
        with mock.patch.object(stats, "fetch", return_value=NO_STAMP), mock.patch("sys.stderr", err):
            code = stats.main()
        self.assertEqual(code, 0)
        self.assertEqual(self.out.read_text(encoding="utf-8"), GOOD_JS)
        self.assertEqual(self.hist.read_text(encoding="utf-8"), GOOD_HIST)
        warning = err.getvalue()
        self.assertIn("no timestamp", warning)
        self.assertIn("keeping last good data", warning)

    def test_unmapped_row_still_fails(self):
        raw = (
            "<h2>Summary status table</h2>"
            "Data last updated: 2026 Nov  2 0045:00"
            "<table><tr><th>Name</th>" + "".join("<th>col</th>" for _ in range(19)) + "</tr>"
            "<tr><td>Starlink Unknown Bus</td>" + "".join(f"<td>{i}</td>" for i in range(19)) + "</tr>"
            "<tr><td>Total</td>" + "".join("<td>1</td>" for _ in range(19)) + "</tr></table>"
            "<h2>List of all Starlink satellites</h2>"
        )
        with mock.patch.object(stats, "fetch", return_value=raw):
            with self.assertRaises(SystemExit) as ctx:
                stats.main()
        self.assertIn("unmapped row", str(ctx.exception))
        self.assertEqual(self.out.read_text(encoding="utf-8"), GOOD_JS)


if __name__ == "__main__":
    unittest.main()
